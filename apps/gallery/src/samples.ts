export function themeLabel(name: string): string {
  switch (name) {
    case "lime-gray":
      return "라임 그레이"
    case "lime-navy":
      return "라임 네이비"
    case "lime-mono":
      return "라임 모노"
    case "lime-gold":
      return "라임 골드"
    case "orange-gray":
      return "오렌지 그레이"
    case "navy-gold":
      return "네이비 골드"
    case "blue-mono":
      return "블루 모노"
    default:
      return name
  }
}
